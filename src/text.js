// 表記を「文字の並び」に。size は倍率、word は言葉の番号
export function parsePhrase(str) {
  const out = [];
  str.split('|').forEach((w, wi) => {
    let size = 1, big = false, t = w;
    if (w.startsWith('{') && w.endsWith('}')) { size = 1.7; big = true; t = w.slice(1, -1); }
    else if (w.startsWith('(') && w.endsWith(')')) { size = 0.7; t = w.slice(1, -1); }
    for (const ch of t) out.push({ ch, size, big, word: wi, space: ch === '　' || ch === ' ' });
  });
  return out;
}

